// The measuring half of ako/mxcli#2292: reads each System entity's element $ID
// out of built `deployment/model/model.mdp` files and regenerates
// system_entity_ids.go.
//
// ONE build is not enough, and that is the finding this test encodes. Most
// System entities carry a fixed $ID that mxbuild ships in
// Mendix.Modeler.Core.dll — System.Language is
// 83d81a7b-4a84-416e-a64f-0ffa981c8408 in a 10.24.4 build, in an 11.16.0 build,
// and in the agent a Studio Pro 11.16 save wrote. But a dozen (PrivateFileDocument,
// Thumbnail, BackgroundJob, ChangeHash, WorkflowVersion, …) are added to the
// System module at load, with an $ID minted for that session: two builds of
// the SAME project disagree on them. A table taken from one build would bake
// in a random id and present it as Studio Pro's. So the generator takes
// several builds and keeps an entity only when at least two of them carry it
// and every one that does agrees.
//
//	go test ./modelsdk/meta -run TestSystemEntityIDsUpdate \
//	    -mdp-ids a/deployment/model/model.mdp,b/deployment/model/model.mdp -update-ids
//
// Use at least two builds of one version (that is what exposes the minted
// ids) and, where you can, a build of another version.
package meta

import (
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"go.mongodb.org/mongo-driver/v2/bson"
)

var (
	mdpIDPaths = flag.String("mdp-ids", "", "comma-separated built model.mdp files to measure System entity $IDs from")
	updateIDs  = flag.Bool("update-ids", false, "regenerate system_entity_ids.go from -mdp-ids")
	idSources  = flag.String("mdp-ids-label", "", "provenance line for the generated file, e.g. '11.16.0 (2 builds), 10.24.4.77222 (1 build)'")
)

func TestSystemEntityIDsUpdate(t *testing.T) {
	if *mdpIDPaths == "" {
		t.Skip("no -mdp-ids given; this test re-measures from built deployment/model/model.mdp files")
	}
	paths := strings.Split(*mdpIDPaths, ",")
	if len(paths) < 2 {
		t.Fatalf("give at least two builds: one build cannot tell a fixed $ID from one minted at load")
	}
	seen := map[string][]string{} // entity -> the $ID each build gave it
	for _, p := range paths {
		raw, err := os.ReadFile(p)
		if err != nil {
			t.Fatalf("read %s: %v", p, err)
		}
		ids := systemEntityIDsFromMDP(raw)
		if len(ids) == 0 {
			t.Fatalf("%s carries no System module domain model — is it a deploy build?", p)
		}
		for name, id := range ids {
			seen[name] = append(seen[name], id)
		}
	}
	keep := map[string]string{}
	var minted, once []string
	for name, ids := range seen {
		switch {
		case len(ids) < 2:
			once = append(once, name)
		case !allEqual(ids):
			minted = append(minted, name)
		default:
			keep[name] = ids[0]
		}
	}
	sort.Strings(minted)
	sort.Strings(once)
	t.Logf("fixed: %d; minted per build (left out): %s; in one build only (left out): %s",
		len(keep), strings.Join(minted, ", "), strings.Join(once, ", "))

	if !*updateIDs {
		for name, want := range keep {
			if got, ok := systemEntityIDs[name]; !ok || got != want {
				t.Errorf("System.%s: table says %q, the builds say %s", name, got, want)
			}
		}
		for name := range systemEntityIDs {
			if _, ok := keep[name]; !ok {
				t.Errorf("System.%s is in the table but not a fixed $ID in these builds", name)
			}
		}
		return
	}
	if *idSources == "" {
		t.Fatalf("pass -mdp-ids-label naming the versions and builds measured; it is the table's provenance")
	}
	names := make([]string, 0, len(keep))
	for n := range keep {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by TestSystemEntityIDsUpdate (system_entity_ids_measure_test.go); DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("package meta\n\n")
	b.WriteString("// systemEntityIDs is each System entity's element $ID, measured from the\n")
	b.WriteString("// System domain model in built deployment/model/model.mdp files:\n")
	fmt.Fprintf(&b, "// %s.\n", *idSources)
	b.WriteString("// Only entities whose $ID every build agreed on are listed; the ones mxbuild\n")
	b.WriteString("// mints at load (two builds of one project disagree) were left out:\n")
	for _, n := range minted {
		fmt.Fprintf(&b, "//   - %s\n", n)
	}
	b.WriteString("var systemEntityIDs = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, keep[n])
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		t.Fatalf("format generated table: %v", err)
	}
	out := filepath.Join(".", "system_entity_ids.go")
	if err := os.WriteFile(out, src, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("rewrote %s with %d entities", out, len(names))
}

func allEqual(ss []string) bool {
	for _, s := range ss[1:] {
		if s != ss[0] {
			return false
		}
	}
	return true
}

// systemEntityIDsFromMDP returns entity name -> element $ID (canonical GUID
// text) for the System module's domain model in a deployed model.mdp. The
// stream layout is the one systemStringLengthsFromMDP documents.
func systemEntityIDsFromMDP(raw []byte) map[string]string {
	out := map[string]string{}
	inSystem := false
	for off := 0; off+4 <= len(raw); {
		size := int(binary.LittleEndian.Uint32(raw[off : off+4]))
		if size < 5 || off+size > len(raw) {
			break
		}
		doc := bson.Raw(raw[off : off+size])
		off += size
		ty, _ := doc.Lookup("$Type").StringValueOK()
		switch ty {
		case "Projects$ModuleImpl":
			name, _ := doc.Lookup("Name").StringValueOK()
			inSystem = name == "System"
		case "DomainModels$DomainModel":
			if !inSystem {
				continue
			}
			inSystem = false
			arr, ok := doc.Lookup("Entities").ArrayOK()
			if !ok {
				continue
			}
			vals, _ := arr.Values()
			for _, v := range vals {
				e, ok := v.DocumentOK()
				if !ok {
					continue
				}
				// The .mdp names an entity by UnqualifiedName; Name is the
				// .mpr spelling, read as a fallback.
				name, _ := e.Lookup("UnqualifiedName").StringValueOK()
				if name == "" {
					name, _ = e.Lookup("Name").StringValueOK()
				}
				_, id, ok := e.Lookup("$ID").BinaryOK()
				if name == "" || !ok || len(id) != 16 {
					continue
				}
				out[name] = netGUIDText(id)
			}
		}
	}
	return out
}

// netGUIDText renders a .NET GUID as stored in BSON (the first three groups
// little-endian) as the canonical text Studio Pro writes into JSON.
func netGUIDText(b []byte) string {
	return fmt.Sprintf("%02x%02x%02x%02x-%02x%02x-%02x%02x-%02x%02x-%x",
		b[3], b[2], b[1], b[0], b[5], b[4], b[7], b[6], b[8], b[9], b[10:])
}

func readGolden(t *testing.T, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", "mxbuild", name+".java.golden"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "\r\n") {
		t.Fatalf("%s has no CRLF — git normalised the golden; see .gitattributes", name)
	}
	return string(b)
}

// Regenerating over the file mxbuild wrote must give that file back, byte for
// byte: this is the steady state of an mxcli edit followed by a build.
func TestGenerateSource_RegeneratesWhatMxbuildWrote(t *testing.T) {
	for _, c := range mxbuildCases {
		if c.userCode == "" {
			continue
		}
		t.Run(c.name, func(t *testing.T) {
			golden := readGolden(t, c.name)
			imports, extra := RetainSections(golden, nil, "")
			got := GenerateSource("MyFirstModule", c.name, c.userCode, c.params, c.ret, imports, extra, "")
			if got != golden {
				t.Errorf("generated source differs from mxbuild's:\n%s", lineDiff(golden, got))
			}
		})
	}
}

// With no file to regenerate over, the import list is the one mxbuild writes
// for a new action. The user code is not compared: mxbuild writes a throwing
// stub there, mxcli the statement's body.
func TestGenerateSource_NewFileMatchesMxbuild(t *testing.T) {
	stub := `throw new com.mendix.systemwideinterfaces.MendixRuntimeException("Java action was not implemented");`
	for _, c := range mxbuildCases {
		if c.userCode != "" {
			continue
		}
		t.Run(c.name, func(t *testing.T) {
			golden := readGolden(t, c.name)
			imports, extra := RetainSections("", nil, "")
			got := GenerateSource("MyFirstModule", c.name, stub, c.params, c.ret, imports, extra, "")
			// mxcli pads the user code with a blank line on each side.
			got = strings.Replace(got, "// BEGIN USER CODE\r\n\r\n", "// BEGIN USER CODE\r\n", 1)
			got = strings.Replace(got, "\r\n\r\n\t\t// END USER CODE", "\r\n\t\t// END USER CODE", 1)
			if got != golden {
				t.Errorf("generated source differs from mxbuild's:\n%s", lineDiff(golden, got))
			}
		})
	}
}

// lineDiff lists the lines that differ, with line endings made visible.
func lineDiff(want, got string) string {
	w, g := strings.SplitAfter(want, "\n"), strings.SplitAfter(got, "\n")
	var sb strings.Builder
	for i := 0; i < len(w) || i < len(g); i++ {
		var wl, gl string
		if i < len(w) {
			wl = w[i]
		}
		if i < len(g) {
			gl = g[i]
		}
		if wl != gl {
			fmt.Fprintf(&sb, "line %d\n  mxbuild: %q\n  mxcli:   %q\n", i+1, wl, gl)
		}
	}
	return sb.String()
}

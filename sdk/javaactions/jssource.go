package javaactions

import (
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"
)

// GenerateJavaScriptSource is JSSource.Generate for an action with no
// documentation and no enumeration values to name.
func GenerateJavaScriptSource(actionName string, userCode string, params []*JavaActionParameter, returnType CodeActionReturnType, imports []string, extraCode string) string {
	return JSSource{Action: actionName, UserCode: userCode, Params: params, ReturnType: returnType,
		Imports: imports, ExtraCode: extraCode}.Generate()
}

// JSSource is what a JavaScript action's .js file is generated from.
type JSSource struct {
	Action        string
	Documentation string // the action's own, written at the top of the JSDoc
	UserCode      string
	Params        []*JavaActionParameter
	ReturnType    CodeActionReturnType
	// Imports and ExtraCode are the sections a regeneration keeps from the
	// existing file (JavaScriptRetainedSections); empty for a new action.
	Imports   []string
	ExtraCode string
	// EnumValues names an enumeration's values, which the JSDoc spells out as
	// a union; nil leaves an enumeration typed as a string.
	EnumValues func(qualifiedName string) []string
}

// importBig is the import mxbuild writes in every JavaScript action file.
const importBig = `import { Big } from "big.js";`

// Generate renders the .js file exactly as mxbuild writes it — CRLF line
// endings included — so a build leaves the file mxcli wrote alone, and a
// re-run of an unchanged script finds nothing to write (ako/mxcli#2357). The
// shape is measured from mxbuild 11.12.6 (--target=deploy) regenerating
// actions mxcli created (testdata/mxbuild/JS_*_11.12.6.js.golden): the banner
// names the import list among what a regeneration keeps; the Big import is
// always there; the action's documentation opens the JSDoc; an optional
// parameter is `[name]`; Integer, Long and Decimal are Big; an object is
// MxObject and a list MxObject[]; an enumeration is the union of its values.
func (s JSSource) Generate() string {
	var sb strings.Builder

	sb.WriteString("// This file was generated by Mendix Studio Pro.\n")
	sb.WriteString("//\n")
	sb.WriteString("// WARNING: Only the following code will be retained when actions are regenerated:\n")
	sb.WriteString("// - the import list\n")
	sb.WriteString("// - the code between BEGIN USER CODE and END USER CODE\n")
	sb.WriteString("// - the code between BEGIN EXTRA CODE and END EXTRA CODE\n")
	sb.WriteString("// Other code you write will be lost the next time you deploy the project.\n")

	for _, imp := range completeJSImports(s.Imports) {
		sb.WriteString(imp + "\n")
	}
	sb.WriteString("\n")

	sb.WriteString("// BEGIN EXTRA CODE\n")
	if strings.TrimSpace(s.ExtraCode) != "" {
		sb.WriteString(strings.TrimRight(s.ExtraCode, "\n") + "\n")
	}
	sb.WriteString("// END EXTRA CODE\n\n")

	sb.WriteString("/**\n")
	if s.Documentation != "" {
		doc := strings.ReplaceAll(strings.ReplaceAll(s.Documentation, "\r\n", "\n"), "\r", "\n")
		for _, line := range strings.Split(doc, "\n") {
			sb.WriteString(" * " + line + "\n")
		}
	}
	for _, p := range s.Params {
		name := JavaScriptParameterName(p.Name)
		if !p.IsRequired {
			name = "[" + name + "]"
		}
		sb.WriteString(fmt.Sprintf(" * @param {%s} %s\n", s.jsDocType(p.ParameterType), name))
	}
	sb.WriteString(fmt.Sprintf(" * @returns {Promise.<%s>}\n", s.jsDocReturn(s.ReturnType)))
	sb.WriteString(" */\n")

	names := make([]string, 0, len(s.Params))
	for _, p := range s.Params {
		names = append(names, JavaScriptParameterName(p.Name))
	}
	sb.WriteString(fmt.Sprintf("export async function %s(%s) {\n", s.Action, strings.Join(names, ", ")))
	sb.WriteString("\t// BEGIN USER CODE\n")
	if strings.TrimSpace(s.UserCode) == "" {
		sb.WriteString("\tthrow new Error(\"JavaScript action '" + s.Action + "' was not implemented\");\n")
	} else {
		for _, line := range strings.Split(strings.TrimRight(s.UserCode, "\n"), "\n") {
			sb.WriteString("\t" + line + "\n")
		}
	}
	sb.WriteString("\t// END USER CODE\n")
	sb.WriteString("}\n")

	// mxbuild writes CRLF, and rewrites an LF file that is otherwise the same.
	out := strings.ReplaceAll(sb.String(), "\r\n", "\n")
	return strings.ReplaceAll(out, "\n", "\r\n")
}

// completeJSImports is the retained import list with the Big import appended
// when it lacks one, deduplicated, in the order found.
func completeJSImports(imports []string) []string {
	out := make([]string, 0, len(imports)+1)
	seen := map[string]bool{}
	for _, imp := range imports {
		if imp = strings.TrimSpace(imp); imp != "" && !seen[imp] {
			seen[imp] = true
			out = append(out, imp)
		}
	}
	if !seen[importBig] {
		out = append(out, importBig)
	}
	return out
}

// JavaScriptParameterName returns the identifier a parameter has in the .js
// file: the model name with its first character lower-cased and the rest
// untouched. This is the rule mxbuild and Studio Pro apply when they regenerate
// the signature and the JSDoc of a JavaScript action, keeping only the user
// code and the EXTRA CODE section. The model name itself is never changed.
//
// Measured with mxbuild 11.12.5 on an action declaring URL, MyID, Some_Name, A,
// XMLData, _Lead, Obj2Name and Eid, which it regenerated as uRL, myID,
// some_Name, a, xMLData, _Lead, obj2Name and eid: only the first character is
// lowered (URL is not url), underscores and later capitals are left alone, and
// a leading underscore has no case. Studio Pro-authored actions agree: the model
// parameters PhoneNumber and Address, GeocodingProvider, ProviderApiKey are
// phoneNumber and address, geocodingProvider, providerApiKey in their .js.
//
// A body written against the declared case therefore throws a ReferenceError
// once mxbuild regenerates the signature, and nothing warns. The signature must
// be generated here the way mxbuild would, so the body sees what will run.
func JavaScriptParameterName(name string) string {
	r, size := utf8.DecodeRuneInString(name)
	if r == utf8.RuneError {
		return name // empty, or not valid UTF-8: leave it as it is
	}
	return string(unicode.ToLower(r)) + name[size:]
}

// jsDocType is a parameter's JSDoc type, as mxbuild writes it.
func (s JSSource) jsDocType(t CodeActionParameterType) string {
	switch typeNameOf(t) {
	case "BooleanType":
		return "boolean"
	case "IntegerType", "LongType", "DecimalType":
		return "Big"
	case "StringType", "StringTemplateParameterType":
		return "string"
	case "DateTimeType":
		return "Date"
	case "EnumerationType":
		return s.enumUnion(t)
	case "EntityType", "FileDocumentType", "TypeParameter":
		return "MxObject"
	case "ListType":
		return "MxObject[]"
	default:
		return "*"
	}
}

// jsDocReturn is a return type's JSDoc type inside Promise.<…>.
func (s JSSource) jsDocReturn(t CodeActionReturnType) string {
	if t == nil {
		return "boolean"
	}
	switch typeNameOf(t) {
	case "BooleanType":
		return "boolean"
	case "IntegerType", "LongType", "DecimalType":
		return "Big"
	case "StringType":
		return "string"
	case "DateTimeType":
		return "Date"
	case "VoidType", "":
		return "void"
	case "EnumerationType":
		return s.enumUnion(t)
	case "ListType":
		return "MxObject[]"
	default:
		return "MxObject"
	}
}

// enumUnion is an enumeration's JSDoc type: undefined or one of its values'
// names — `undefined|"Red"|"Blue"`. Without its values it is a string.
func (s JSSource) enumUnion(t any) string {
	qn := ""
	if e, ok := t.(*EnumerationType); ok {
		qn = e.Enumeration
	}
	var values []string
	if s.EnumValues != nil && qn != "" {
		values = s.EnumValues(qn)
	}
	if len(values) == 0 {
		return "string"
	}
	parts := []string{"undefined"}
	for _, v := range values {
		parts = append(parts, `"`+v+`"`)
	}
	return strings.Join(parts, "|")
}

// typeNameOf returns the short Go type name of a code-action type element
// (e.g. "*javaactions.StringType" → "StringType"), used for JSDoc mapping.
func typeNameOf(t any) string {
	if t == nil {
		return ""
	}
	s := fmt.Sprintf("%T", t)
	if i := strings.LastIndex(s, "."); i >= 0 {
		s = s[i+1:]
	}
	return s
}

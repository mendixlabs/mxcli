// copyProjectToTemp copies the project that holds mprPath into a fresh
// temporary directory, so mx can be run there instead of on the user's project
// (ako/mxcli#951, #961).
//
// Every mx tool writes into the project it is given: update-widgets rewrites
// the model (and converts MPRv2 to MPRv1), mx check compiles the theme into
// theme-cache/ and writes deployment/sass/, and MxBuild regenerates javasource/
// proxies, the .launch/.classpath/.project files and all of deployment/. A
// snapshot/restore of the v2 storage covered only the model, and only on v2 — an
// MPRv1 project's .mpr was rewritten permanently by a "check" or a "build".
//
// Only what mx reads is copied: build output, caches and VCS metadata are skipped
// (copyProjectTree), so the cost is the model plus the widget, theme and source
// folders. cleanup removes the copy; it is never nil and safe to defer.
func copyProjectToTemp(mprPath string, skip ...string) (workMpr string, cleanup func(), err error) {
	cleanup = func() {}
	abs, err := filepath.Abs(mprPath)
	if err != nil {
		return "", cleanup, err
	}
	if info, err := os.Stat(abs); err != nil {
		return "", cleanup, err
	} else if info.IsDir() {
		return "", cleanup, fmt.Errorf("%s is a directory, not a project file", abs)
	}
	tmp, err := os.MkdirTemp("", "mxcli-copy-*")
	if err != nil {
		return "", cleanup, err
	}
	cleanup = func() { os.RemoveAll(tmp) }

	projectDir := filepath.Dir(abs)
	dst := filepath.Join(tmp, filepath.Base(projectDir))
	if err := copyProjectTree(projectDir, dst, skip...); err != nil {
		cleanup()
		return "", func() {}, err
	}
	return filepath.Join(dst, filepath.Base(abs)), cleanup, nil
}

// checkCopySkipRoot are top-level project folders mx neither needs nor should
// see: build output and caches it regenerates. .docker/ holds `docker build`'s
// own output directory, which MxBuild writes to by absolute path.
var checkCopySkipRoot = map[string]bool{
	"deployment":    true, // MxBuild / mx check output
	"releases":      true, // exported .mda packages
	"theme-cache":   true, // compiled theme, regenerated by mx check
	".mendix-cache": true,
	".mxcli":        true, // catalog cache, widget docs
	".docker":       true, // docker init output
}

// checkCopySkipAnywhere are folder names skipped at any depth.
var checkCopySkipAnywhere = map[string]bool{
	".git":         true,
	".svn":         true,
	".hg":          true,
	"node_modules": true,
}

// copyProjectTree copies src to dst, skipping the folders above and any folder
// named in skip (compared as the same directory, so spelling and case do not
// matter; src itself is never skipped). A symlinked file is copied as a file, so a
// tool writing to the copy cannot write through it into the original; a symlinked
// folder is recreated as a link.
func copyProjectTree(src, dst string, skip ...string) error {
	var skipInfos []fs.FileInfo
	for _, s := range skip {
		if info, err := os.Stat(s); err == nil && info.IsDir() {
			skipInfos = append(skipInfos, info)
		}
	}
	return filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			if p == dst || p == filepath.Dir(dst) {
				// $TMPDIR inside the project: do not copy the copy into itself.
				return filepath.SkipDir
			}
			if rel != "." && (checkCopySkipAnywhere[d.Name()] || (!strings.ContainsRune(rel, filepath.Separator) && checkCopySkipRoot[rel])) {
				return filepath.SkipDir
			}
			if rel != "." && len(skipInfos) > 0 {
				if info, err := d.Info(); err == nil {
					for _, s := range skipInfos {
						if os.SameFile(info, s) {
							return filepath.SkipDir
						}
					}
				}
			}
			return os.MkdirAll(target, 0o755)
		}
		if d.Type()&fs.ModeSymlink != 0 {
			info, err := os.Stat(p)
			if err != nil {
				return nil // dangling link: nothing mx could read either
			}
			if info.IsDir() {
				link, err := os.Readlink(p)
				if err != nil {
					return err
				}
				return os.Symlink(link, target)
			}
		} else if !d.Type().IsRegular() {
			return nil // sockets, pipes, devices
		}
		return copyFile(p, target)
	})
}

// pathRewriter forwards output line by line with the temporary copy's path
// replaced by the project's own, so what mx reports names the files the user
// has, not a directory that is deleted when the check ends.
type pathRewriter struct {
	mu   sync.Mutex
	w    io.Writer
	from []string
	to   string
	buf  bytes.Buffer
}

func newPathRewriter(w io.Writer, copyDir, projectDir string) *pathRewriter {
	from := []string{copyDir}
	if resolved, err := filepath.EvalSymlinks(copyDir); err == nil && resolved != copyDir {
		from = append(from, resolved)
	}
	return &pathRewriter{w: w, from: from, to: projectDir}
}

func (r *pathRewriter) Write(p []byte) (int, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.buf.Write(p)
	for {
		i := bytes.IndexByte(r.buf.Bytes(), '\n')
		if i < 0 {
			break
		}
		line := string(r.buf.Next(i + 1))
		if _, err := io.WriteString(r.w, r.rewrite(line)); err != nil {
			return len(p), err
		}
	}
	return len(p), nil
}

// Flush writes a trailing partial line.
func (r *pathRewriter) Flush() {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.buf.Len() > 0 {
		io.WriteString(r.w, r.rewrite(r.buf.String()))
		r.buf.Reset()
	}
}

func (r *pathRewriter) rewrite(s string) string {
	for _, f := range r.from {
		s = strings.ReplaceAll(s, f, r.to)
	}
	return s
}

// WithProjectCopy runs fn with the path of a temporary copy of the project that
// holds mprPath, and removes the copy afterwards. It is for callers that run an
// mx command which writes into the project it is given (theme-cache/,
// deployment/sass/, a module's themesource/ folder) but must leave the user's
// project alone — the same copy Check and MxCheckOnCopy use.
//
// Folders named in skip are left out of the copy — an output folder inside the
// project, whose earlier contents mx has no use for. Naming the project's own
// folder skips nothing.
//
// Output naming the copy should be reported against the project: replace
// filepath.Dir(workMpr) with the project's directory.
func WithProjectCopy(mprPath string, fn func(workMpr string) error, skip ...string) error {
	abs, err := filepath.Abs(mprPath)
	if err != nil {
		return err
	}
	workMpr, cleanup, err := copyProjectToTemp(abs, skip...)
	if err != nil {
		return fmt.Errorf("copy the project to a temporary directory: %w\n"+
			"  set TMPDIR to a disk with room for the project", err)
	}
	defer cleanup()
	return fn(workMpr)
}

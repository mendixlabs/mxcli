// Studio Pro's regeneration of a JavaScript action keeps the import list and
// the code between BEGIN EXTRA CODE and END EXTRA CODE. MDL can express neither
// (describe prints the extra code only as a comment), so a `create or modify`
// with an edited body must carry both over from the file on disk — otherwise a
// hand-restored helper is overwritten and the user code calling it breaks
// (mendixlabs/mxcli#1429).
const storedDistanceJS = `// This file was generated by Mendix Studio Pro.
//
// WARNING: Only the following code will be retained when actions are regenerated:
// - the import list
// - the code between BEGIN USER CODE and END USER CODE
// - the code between BEGIN EXTRA CODE and END EXTRA CODE
// Other code you write will be lost the next time you deploy the project.
import "mx-global";
import { Big } from "big.js";
import {
	sin,
	cos
} from "./trig";

// BEGIN EXTRA CODE
function deg2rad(deg) {
    return deg.times(Math.PI / 180);
}
// END EXTRA CODE

/**
 * @param {Big} latitude
 * @returns {Promise.<Big>}
 */
export async function GetDistance(latitude) {
	// BEGIN USER CODE
	return deg2rad(latitude);
	// END USER CODE
}
`

func TestWriteJavaScriptSourceFile_EditedBodyKeepsImportsAndExtraCode(t *testing.T) {
	dir := t.TempDir()
	b := &Backend{path: filepath.Join(dir, "App.mpr")}
	jsDir := b.jsActionSourceDir("WebMod")
	if err := os.MkdirAll(jsDir, 0o755); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(jsDir, "GetDistance.js")
	if err := os.WriteFile(path, []byte(storedDistanceJS), 0o644); err != nil {
		t.Fatal(err)
	}

	params := []*types.JavaActionParameter{{Name: "latitude", IsRequired: true, ParameterType: &types.DecimalType{}}}
	if err := b.WriteJavaScriptSourceFile("WebMod", "GetDistance", "return deg2rad(latitude).times(2);", params, &types.DecimalType{}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	src := string(got)
	for _, want := range []string{
		`import "mx-global";`,
		`import { Big } from "big.js";`,
		"import {\n\tsin,\n\tcos\n} from \"./trig\";",
		"// BEGIN EXTRA CODE\nfunction deg2rad(deg) {\n    return deg.times(Math.PI / 180);\n}\n// END EXTRA CODE",
		"\treturn deg2rad(latitude).times(2);",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("regenerated source lost %q:\n%s", want, src)
		}
	}
	// The imports precede the EXTRA CODE section, as Studio Pro writes them.
	if strings.Index(src, `import { Big }`) > strings.Index(src, "// BEGIN EXTRA CODE") {
		t.Errorf("imports written after the EXTRA CODE section:\n%s", src)
	}

	// Regenerating again is stable: nothing duplicated.
	if err := b.WriteJavaScriptSourceFile("WebMod", "GetDistance", "return deg2rad(latitude).times(2);", params, &types.DecimalType{}); err != nil {
		t.Fatal(err)
	}
	again, _ := os.ReadFile(path)
	if string(again) != src {
		t.Errorf("second regeneration changed the file:\n%s", again)
	}
}

// Control: with no file on disk the stub is the plain generated one — no
// imports and an empty EXTRA CODE section.
func TestWriteJavaScriptSourceFile_NewFileHasEmptySections(t *testing.T) {
	dir := t.TempDir()
	b := &Backend{path: filepath.Join(dir, "App.mpr")}
	if err := b.WriteJavaScriptSourceFile("WebMod", "Fresh", "return 1;", nil, nil); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(b.jsActionSourceDir("WebMod"), "Fresh.js"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(got), "\nimport ") || !strings.Contains(string(got), "// BEGIN EXTRA CODE\n// END EXTRA CODE") {
		t.Errorf("new stub has unexpected sections:\n%s", got)
	}
}

// mxbuild and Studio Pro regenerate a JavaScript action's signature with the
// first character of each parameter name lower-cased and keep the body, so the
// file mxcli writes has to carry those names or the body is written against
// identifiers that stop existing at the next build.
func TestWriteJavaScriptSourceFile_ParametersAreLowerFirst(t *testing.T) {
	dir := t.TempDir()
	b := &Backend{path: filepath.Join(dir, "App.mpr")}
	params := []*types.JavaActionParameter{
		{Name: "Url", ParameterType: &types.StringType{}},
		{Name: "ReadOnly", ParameterType: &types.BooleanType{}},
	}
	if err := b.WriteJavaScriptSourceFile("Demo", "JS_Open", `return url + (readOnly ? " (read only)" : "");`, params, &types.StringType{}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(b.jsActionSourceDir("Demo"), "JS_Open.js"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		" * @param {string} url\n",
		" * @param {boolean} readOnly\n",
		"export async function JS_Open(url, readOnly) {\n",
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("source lacks %q:\n%s", want, got)
		}
	}
}

// Rewriting an action authored in Studio Pro must reproduce the signature it
// has: the model declares Address, the file says address, and the body uses
// address. Before, the rewrite turned the signature into Address while the body
// kept address.
func TestWriteJavaScriptSourceFile_RewriteKeepsStudioProSignature(t *testing.T) {
	const stored = `// This file was generated by Mendix Studio Pro.
import { Big } from "big.js";

// BEGIN EXTRA CODE
// END EXTRA CODE

/**
 * @param {string} [address]
 * @param {string} [geocodingProvider]
 * @param {string} [providerApiKey]
 * @returns {Promise.<string>}
 */
export async function Locate(address, geocodingProvider, providerApiKey) {
	// BEGIN USER CODE
	return address + geocodingProvider;
	// END USER CODE
}
`
	dir := t.TempDir()
	b := &Backend{path: filepath.Join(dir, "App.mpr")}
	jsDir := b.jsActionSourceDir("Demo")
	if err := os.MkdirAll(jsDir, 0o755); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(jsDir, "Locate.js")
	if err := os.WriteFile(path, []byte(stored), 0o644); err != nil {
		t.Fatal(err)
	}
	params := []*types.JavaActionParameter{
		{Name: "Address", ParameterType: &types.StringType{}},
		{Name: "GeocodingProvider", ParameterType: &types.StringType{}},
		{Name: "ProviderApiKey", ParameterType: &types.StringType{}},
	}
	if err := b.WriteJavaScriptSourceFile("Demo", "Locate", "return address + geocodingProvider + providerApiKey;", params, &types.StringType{}); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(path)
	const sig = "export async function Locate(address, geocodingProvider, providerApiKey) {\n"
	if !strings.Contains(string(got), sig) {
		t.Errorf("rewrite changed the Studio Pro signature:\n%s", got)
	}
	for _, name := range []string{"address", "geocodingProvider", "providerApiKey"} {
		if !strings.Contains(string(got), " "+name+"\n") {
			t.Errorf("JSDoc lost @param %s:\n%s", name, got)
		}
	}
}
